def generate_content(content_type="instagram_caption", topic="brand update", model="hermes-4"):
    """Construct a prompt baking in BRAND voice rules, tone_rules, and banned_words."""
    brand = BRAND
    instruction = brand["content_types"].get(
        content_type,
        brand["content_types"].get("instagram_caption", "Write brand-voice content."),
    )
    rules_block = "\\n".join(f"- {r}" for r in brand["tone_rules"])
    bans_block = "\\n".join(f"- {w}" for w in brand["banned_words"])

    prompt = (
        f"You are the voice of {brand['name']}. "
        f"Voice: {brand['voice']}\\n\\n"
        f"Tone rules:\\n{rules_block}\\n\\n"
        f"Banned words — NEVER use these:\\n{bans_block}\\n\\n"
        f"Task: {instruction}\\n\\n"
        f"Topic: {topic}\\n\\n"
        f"Generate brand-voice content for: {topic}"
    )
    return prompt


