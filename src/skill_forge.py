def _to_slug(name: str) -> str:
    normalized = name.lower().strip()
    normalized = unicodedata.normalize("NFKD", normalized)
    normalized = "".join(c for c in normalized if not unicodedata.combining(c))
    normalized = re.sub(r"[^a-z0-9]+", "_", normalized)
    normalized = re.sub(r"_+", "_", normalized)
    return normalized.strip("_")


def _render_code(profile: BrandProfile) -> str:
    slug = _to_slug(profile.name)
    brand_name = profile.name
    voice = profile.voice_tone or "professional and clear"
    primary = profile.primary_color or "#000000"
    secondary = profile.secondary_color or "#ffffff"
    display = profile.display_font or "Inter"
    body = profile.body_font or "Inter"
    tagline = profile.tagline or ""
    tone_rules = profile.voice_dos or []
    donts = profile.voice_donts or []

    banned_words = list(_ABSOLUTE_BANS)
    for item in donts:
        if item and item.lower() not in (w.lower() for w in banned_words):
            banned_words.append(item)

    content_types_repr = repr({k: v for k, v in _CONTENT_TYPE_INSTRUCTIONS.items()})

    tone_rules_repr = repr([str(r) for r in tone_rules])
    banned_words_repr = repr([str(w) for w in banned_words])

    code = _SKILL_CODE_TEMPLATE.substitute(
        brand_name_repr=repr(brand_name),
        voice_repr=repr(voice),
        primary_repr=repr(primary),
        secondary_repr=repr(secondary),
        display_repr=repr(display),
        body_repr=repr(body),
        tagline_repr=repr(tagline),
        tone_rules_repr=tone_rules_repr,
        content_types_repr=content_types_repr,
        banned_words_repr=banned_words_repr,
        brand_name=brand_name,
    )

    return code


def forge_skill(profile: BrandProfile, output_dir: str = "./output/skills/") -> str:
    code = _render_code(profile)
    expanded = os.path.expanduser(output_dir)
    os.makedirs(expanded, exist_ok=True)
    slug = _to_slug(profile.name)
    filename = f"brand_{slug}_content.py"
    path = os.path.join(expanded, filename)
    with open(path, "w") as f:
        f.write(code)
    return path


def forge_skill_preview(profile: BrandProfile) -> str:
    return _render_code(profile)
